#!/usr/bin/env python3
import argparse
import json
import re
import sys
from pathlib import Path

ACTIONS = (
    "get_design_context",
    "get_metadata",
    "get_screenshot",
    "get_image",
    "download_assets",
    "get_variable_defs",
    "search_design_system",
    "get_libraries",
)

EXPLANATIONS = {
    "get_design_context": (
        "Implementation spec — layout, styles, spacing, generated code"
    ),
    "get_metadata": "Node/frame tree and dimensions",
    "get_screenshot": "Visual reference only — not for shipped assets",
    "get_image": "Rendered node PNG (base64) — use with --save-files",
    "download_assets": (
        "Plugin MCP only — not on desktop Dev Mode server; use "
        "get_design_context + --save-files for SVG/localhost assets"
    ),
    "get_variable_defs": "Variable definitions resolved on a frame/node",
    "search_design_system": "Design-system search — components, variables, styles",
    "get_libraries": "Libraries subscribed/available for a file",
}

GENERATED_BY = "Auto-generated by the fc skill's `figma_cache_index.py`."


def category_title(slug, titles):
    return titles.get(slug) or slug.replace("-", " ").title()


def node_id_colon(node_hyphen):
    if not node_hyphen or node_hyphen == "pages":
        return None
    return node_hyphen.replace("-", ":")


def first_text_content(response):
    content = response.get("content")
    if not isinstance(content, list):
        return ""
    for item in content:
        if isinstance(item, dict) and item.get("type") == "text":
            text = item.get("text")
            if isinstance(text, str) and text.strip():
                return text
    return ""


def layer_name_from_design_context(text, node_hyphen):
    node_colon = node_id_colon(node_hyphen)
    if node_colon:
        pattern = (
            rf'data-node-id="{re.escape(node_colon)}"[^>]*data-name="([^"]+)"'
        )
        match = re.search(pattern, text)
        if match:
            return match.group(1)
        pattern = (
            rf'data-name="([^"]+)"[^>]*data-node-id="{re.escape(node_colon)}"'
        )
        match = re.search(pattern, text)
        if match:
            return match.group(1)
        pattern = rf'id="{re.escape(node_colon)}" name="([^"]+)"'
        match = re.search(pattern, text)
        if match:
            return match.group(1)
    match = re.search(r'data-name="([^"]+)"', text)
    if match:
        return match.group(1)
    match = re.search(r"export default function (\w+)", text)
    if match:
        return match.group(1)
    return "—"


def layer_name_from_metadata(text, node_hyphen):
    node_colon = node_id_colon(node_hyphen)
    if node_colon:
        pattern = rf'id="{re.escape(node_colon)}" name="([^"]+)"'
        match = re.search(pattern, text)
        if match:
            return match.group(1)
    match = re.search(r'name="([^"]+)"', text)
    if match:
        return match.group(1)
    return "—"


def layer_name(payload):
    action = payload.get("action", "")
    node_id = payload.get("nodeId")
    if action == "search_design_system":
        query = payload.get("searchQuery") or "—"
        return f"search: {query}"
    if action == "get_libraries":
        offset = payload.get("librariesOffset")
        if offset is not None:
            return f"libraries (offset {offset})"
        return "libraries"
    if node_id == "pages" or (action == "get_metadata" and not node_id):
        return "Document pages"

    response = payload.get("response") or {}
    text = first_text_content(response)

    if action == "get_design_context":
        return layer_name_from_design_context(text, node_id)
    if action == "get_metadata":
        return layer_name_from_metadata(text, node_id)
    if action == "get_variable_defs":
        blob = parse_json_blob(text)
        if isinstance(blob, dict) and blob:
            return f"variables ({len(blob)} keys)"
        return "variables"
    return "—"


def parse_json_blob(text):
    text = (text or "").strip()
    if not text:
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        try:
            return json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            return None
    return None


def explanation_for(action):
    return EXPLANATIONS.get(action, "Cached Figma MCP response")


def repo_root(cache_root):
    for parent in (cache_root, *cache_root.parents):
        if (parent / ".git").exists():
            return parent
    return None


def relative_cache_path(cache_root, path):
    root = repo_root(cache_root)
    if root is None:
        return str(path)
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def cache_entry_key(payload, path):
    action = payload.get("action", "")
    if action in ("search_design_system", "get_libraries"):
        return path.stem
    file_key = payload.get("fileKey")
    node_id = payload.get("nodeId") or "pages"
    if file_key:
        return f"{file_key}__{node_id}"
    stem = path.stem
    return stem


def parse_simple_yaml(text):
    data = {
        "fallback": "other",
        "node_ids": {},
        "layer_names": {},
        "patterns": {},
        "titles": {},
    }
    section = None
    current_category = None

    for raw_line in text.splitlines():
        line = raw_line.split("#", 1)[0].rstrip()
        if not line.strip():
            continue

        if not line.startswith((" ", "\t")) and ": " in line:
            key, value = line.split(":", 1)
            key = key.strip()
            value = value.strip()
            if key == "fallback":
                data["fallback"] = value
                section = None
                current_category = None
                continue

        if not line.startswith((" ", "\t")) and line.endswith(":") and ": " not in line:
            key = line[:-1].strip()
            if key in data:
                section = key
                current_category = None
            continue

        if section in ("layer_names", "patterns"):
            stripped = line.strip()
            if stripped.startswith("- "):
                if current_category:
                    data[section][current_category].append(stripped[2:].strip())
            elif stripped.endswith(":"):
                current_category = stripped[:-1].strip()
                data[section].setdefault(current_category, [])
            continue

        if section in ("node_ids", "titles"):
            if ":" in line:
                key, value = line.split(":", 1)
                data[section][key.strip()] = value.strip()

    return data


def load_categories(cache_root):
    config_path = cache_root / "categories.yml"
    fallback = "other"
    node_ids = {}
    layer_names = {}
    patterns = {}
    titles = {}

    if not config_path.is_file():
        return fallback, node_ids, layer_names, patterns, titles

    data = parse_simple_yaml(config_path.read_text(encoding="utf-8"))
    fallback = data.get("fallback", "other")
    node_ids = data.get("node_ids") or {}
    layer_names = data.get("layer_names") or {}
    patterns = data.get("patterns") or {}
    titles = data.get("titles") or {}
    return fallback, node_ids, layer_names, patterns, titles


def normalize_layer_name(name):
    return (name or "").strip().casefold()


def category_for_row(row, entry_key, fallback, node_ids, layer_names, patterns):
    if entry_key in node_ids:
        return node_ids[entry_key]

    layer_cf = normalize_layer_name(row["layer_name"])
    for category, names in layer_names.items():
        for name in names:
            if layer_cf == normalize_layer_name(name):
                return category

    layer_raw = row["layer_name"] or ""
    for category, fragments in patterns.items():
        for fragment in fragments:
            if fragment in layer_raw:
                return category

    return fallback


def collect_rows(cache_root):
    rows = []
    for action in ACTIONS:
        action_dir = cache_root / action
        if not action_dir.is_dir():
            continue
        for path in sorted(action_dir.glob("*.json")):
            try:
                payload = json.loads(path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError):
                continue
            entry_key = cache_entry_key(payload, path)
            rows.append(
                {
                    "layer_name": layer_name(payload),
                    "action": payload.get("action", action),
                    "cache_file": relative_cache_path(cache_root, path),
                    "explanation": explanation_for(payload.get("action", action)),
                    "cached_datetime": payload.get("cachedAt", "—"),
                    "entry_key": entry_key,
                }
            )
    rows.sort(key=lambda row: row["cached_datetime"], reverse=True)
    return rows


def assign_categories(rows, cache_root):
    fallback, node_ids, layer_names, patterns, _ = load_categories(cache_root)
    for row in rows:
        row["category"] = category_for_row(
            row, row["entry_key"], fallback, node_ids, layer_names, patterns
        )
    return rows


def escape_cell(value):
    return str(value).replace("|", "\\|")


def render_category_file(category, rows, titles):
    title = category_title(category, titles)
    lines = [
        f"# Figma cache — {title}",
        "",
        GENERATED_BY,
        "Categorization rules: `categories.yml` in this folder.",
        "",
        "| Layer name | Action | Cache file | Explanation | cached_datetime |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {escape_cell(row['layer_name'])} | {row['action']} | "
            f"`{escape_cell(row['cache_file'])}` | "
            f"{escape_cell(row['explanation'])} | {row['cached_datetime']} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_hub(rows, titles):
    by_category = {}
    for row in rows:
        by_category.setdefault(row["category"], []).append(row)

    category_slugs = sorted(
        by_category.keys(),
        key=lambda slug: (slug not in titles, category_title(slug, titles)),
    )

    lines = [
        "# Figma cache index",
        "",
        GENERATED_BY,
        "Do not edit by hand — run the script or `/fc` after a new cache",
        "write to refresh.",
        "",
        "Browse by category (edit rules in `categories.yml`):",
        "",
    ]
    for slug in category_slugs:
        title = category_title(slug, titles)
        count = len(by_category[slug])
        lines.append(f"- [{title}](./{slug}.md) — {count} entries")

    lines.extend(
        [
            "",
            f"**Total:** {len(rows)} cached files",
            "",
        ]
    )
    return "\n".join(lines)


def write_category_files(rows, cache_root, titles):
    by_category = {}
    for row in rows:
        by_category.setdefault(row["category"], []).append(row)

    written = []
    for category, category_rows in sorted(by_category.items()):
        out_path = cache_root / f"{category}.md"
        out_path.write_text(
            render_category_file(category, category_rows, titles),
            encoding="utf-8",
        )
        written.append(out_path)

    known_slugs = set(by_category.keys())
    ignore = {"INDEX", "README"}
    for path in cache_root.glob("*.md"):
        if path.stem in ignore:
            continue
        if path.stem not in known_slugs:
            path.unlink()
            print(f"removed empty category: {path}")

    return written


def main():
    parser = argparse.ArgumentParser(
        description="Rebuild the Figma cache index and category markdown files."
    )
    parser.add_argument(
        "--cache-root",
        default="figma/cache",
        help="Path to the Figma cache directory",
    )
    args = parser.parse_args()

    cache_root = Path(args.cache_root).resolve()
    if not cache_root.is_dir():
        print(f"Cache root not found: {cache_root}", file=sys.stderr)
        return 1

    titles = load_categories(cache_root)[4]
    rows = assign_categories(collect_rows(cache_root), cache_root)
    hub_path = cache_root / "INDEX.md"
    hub_path.write_text(render_hub(rows, titles), encoding="utf-8")

    category_files = write_category_files(rows, cache_root, titles)
    category_count = len({row["category"] for row in rows})
    print(
        f"index written: {hub_path} ({len(rows)} entries, "
        f"{category_count} categories)"
    )
    for path in sorted(category_files):
        print(f"  category: {path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
